/* Compile reviewed local copy. No translation service or user data is involved. */
const fs = require('node:fs');
const path = require('node:path');
const engine = require('../assessment-assets/discovery-model.js');
const root = path.resolve(__dirname, '..');
function rows(file) {
  return fs.readFileSync(path.join(root, 'content', file), 'utf8').replace(/\n+$/, '').normalize('NFC').split('\n').slice(1).map((line, index) => {
    const values = line.split('\t');
    if (values.some(value => !value.trim())) throw new Error(file + ': empty cell at row ' + (index + 2));
    return values;
  });
}
const copy = Object.fromEntries(['bg', 'ro'].map(code => [code, { terms: {}, questions: {}, actions: {}, report: {}, budget: {} }]));
for (const file of ['tool-terms.tsv', 'tool-interface.tsv', 'tool-paragraphs.tsv']) {
  for (const [key, bg, ro, extra] of rows(file)) {
    if (!bg || !ro || extra) throw new Error('Invalid translation row: ' + file + ' / ' + key);
    for (const [code, text] of Object.entries({ bg, ro })) {
      if (copy[code].terms[key] && copy[code].terms[key] !== text) throw new Error('Conflicting translation: ' + key);
      copy[code].terms[key] = text;
    }
  }
}
for (const [id, bgTitle, roTitle, bgHelp, roHelp] of rows('tool-questions.tsv')) {
  if (!engine.questions.some(q => q.id === id)) throw new Error('Unknown question ' + id);
  copy.bg.questions[id] = { title: bgTitle, help: bgHelp };
  copy.ro.questions[id] = { title: roTitle, help: roHelp };
}
for (const [file, section] of [['tool-actions.tsv', 'actions'], ['tool-report.tsv', 'report'], ['tool-budget.tsv', 'budget']]) {
  for (const [key, bg, ro] of rows(file)) { copy.bg[section][key] = bg; copy.ro[section][key] = ro; }
}
for (const [code, data] of Object.entries(copy)) {
  for (const q of engine.questions) {
    if (!data.questions[q.id] || !data.terms[q.area]) throw new Error(code + ': missing question ' + q.id);
    for (const f of q.fields) {
      if (!data.terms[f.label] || !data.actions[f.key]) throw new Error(code + ': missing field ' + f.key);
      for (const o of f.choices) if (!data.terms[o.label]) throw new Error(code + ': missing option ' + o.label);
    }
  }
}
fs.writeFileSync(path.join(root, 'assets/i18n/tool-copy.js'), '/* Generated by scripts/tool-locales.cjs. Edit content/tool-*.tsv. */\n' +
  '(function(root,data){if(typeof module==="object"&&module.exports)module.exports=data;else root.QuarkToolCopy=data;})(typeof globalThis==="object"?globalThis:this,' + JSON.stringify(copy, null, 2).replace(/</g, '\\u003c') + ');\n');
console.log('Compiled BG/RO tool copy: ' + engine.questions.length + ' question groups.');
