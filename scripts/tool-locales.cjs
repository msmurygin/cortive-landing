/* Compile reviewed local copy. No translation service or user data is involved. */
const fs = require('node:fs');
const path = require('node:path');
const engine = require('../assessment-assets/discovery-model.js');
const root = path.resolve(__dirname, '..');
const languages = ['bg', 'ro', 'el', 'sr'];
function rows(file, columns) {
  return fs.readFileSync(path.join(root, 'content', file), 'utf8').replace(/\n+$/, '').normalize('NFC').split('\n').slice(1).map((line, index) => {
    const values = line.split('\t');
    if (values.length !== columns || values.some(value => !value.trim())) throw new Error(file + ': invalid cells at row ' + (index + 2));
    return values;
  });
}
const copy = Object.fromEntries(languages.map(code => [code, { terms: {}, questions: {}, actions: {}, report: {}, budget: {} }]));
function readPairs(file, section, codes) {
  for (const [key, ...translations] of rows(file, codes.length + 1)) {
    codes.forEach((code, index) => {
      const previous = copy[code][section][key], text = translations[index];
      if (previous && previous !== text) throw new Error(code + ': conflicting translation: ' + key);
      copy[code][section][key] = text;
    });
  }
}
function readQuestions(file, codes) {
  for (const [id, firstTitle, secondTitle, firstHelp, secondHelp] of rows(file, 5)) {
    if (!engine.questions.some(q => q.id === id)) throw new Error('Unknown question ' + id);
    copy[codes[0]].questions[id] = { title: firstTitle, help: firstHelp };
    copy[codes[1]].questions[id] = { title: secondTitle, help: secondHelp };
  }
}
for (const file of ['tool-terms.tsv', 'tool-interface.tsv', 'tool-paragraphs.tsv']) readPairs(file, 'terms', ['bg', 'ro']);
readQuestions('tool-questions.tsv', ['bg', 'ro']);
for (const section of ['actions', 'report', 'budget']) readPairs('tool-' + section + '.tsv', section, ['bg', 'ro']);
for (const file of ['tool-el-sr-terms.tsv', 'tool-el-sr-paragraphs.tsv']) readPairs(file, 'terms', ['el', 'sr']);
readQuestions('tool-el-sr-questions.tsv', ['el', 'sr']);
for (const section of ['actions', 'report', 'budget']) readPairs('tool-el-sr-' + section + '.tsv', section, ['el', 'sr']);
for (const [code, data] of Object.entries(copy)) {
  for (const section of Object.keys(copy.bg)) {
    const missing = Object.keys(copy.bg[section]).filter(key => !Object.hasOwn(data[section], key));
    const extra = Object.keys(data[section]).filter(key => !Object.hasOwn(copy.bg[section], key));
    if (missing.length || extra.length) throw new Error(code + '/' + section + ': missing=' + JSON.stringify(missing) + '; unexpected=' + JSON.stringify(extra));
  }
  for (const q of engine.questions) {
    if (!data.questions[q.id] || !data.terms[q.area]) throw new Error(code + ': missing question ' + q.id);
    for (const f of q.fields) {
      if (!data.terms[f.label] || !data.actions[f.key]) throw new Error(code + ': missing field ' + f.key);
      for (const o of f.choices) if (!data.terms[o.label]) throw new Error(code + ': missing option ' + o.label);
    }
  }
}
fs.writeFileSync(path.join(root, 'assets/i18n/tool-copy.js'), '/* Generated by scripts/tool-locales.cjs. Edit content/tool-*.tsv. */\n' +
  '(function(root,data){if(typeof module==="object"&&module.exports)module.exports=data;else root.QuarkToolCopy=data;})(typeof globalThis==="object"?globalThis:this,' + JSON.stringify(copy, null, 2).replace(/</g, '\\u003c') + ');\n');
console.log('Compiled ' + languages.join('/') + ' tool copy: ' + engine.questions.length + ' question groups.');
